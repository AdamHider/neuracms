<?php

declare(strict_types=1);

namespace FlatCms\Content;

use FlatCms\Contracts\Subsystem;
use FlatCms\Core\Config;
use FlatCms\Core\Events;
use FlatCms\Support\Fs;

/**
 * Lightweight index over content/. Built from Storage and written to
 * var/cache/index.php through var_export so OPcache keeps it in memory.
 */
final class Index implements Subsystem
{
    /** @var array<string, array<string, mixed>> */
    private array $entries = [];

    private int $stamp = 0;

    private bool $loaded = false;

    public function __construct(
        private readonly Fs $fs,
        private readonly Storage $storage,
        private readonly Schema $schema,
        private readonly Events $events,
        private readonly Config $config,
    ) {
    }

    public function boot(\FlatCms\App $app): void
    {
        $this->load();
    }

    public function build(): void
    {
        $this->entries = [];
        $stamp = 0;

        foreach ($this->storage->scan() as $id) {
            $item = $this->storage->load($id);
            if ($item === null) {
                continue;
            }

            $stamp = max($stamp, $this->fs->mtime($this->storage->base() . '/' . ($id === '' ? '' : $id)));

            $this->entries[$id] = [
                'id' => $item->id(),
                'type' => $item->type(),
                'kind' => $this->schema->kind($item->type()),
                'url' => $item->url(),
                'title' => $item->title(),
                'slug' => $item->slug(),
                'parent' => $item->parentId(),
                'order' => $item->order(),
                'date' => $item->date(),
                'published' => $item->published(),
                'indexed' => $this->indexedValues($item),
            ];
        }

        $this->stamp = time();
        $this->loaded = true;
        $this->persist();
        $this->events->emit('index.built', $this);
    }

    public function get(string $id): ?array
    {
        $this->load();

        return $this->entries[$id] ?? null;
    }

    public function all(): array
    {
        $this->load();

        return $this->entries;
    }

    public function isStale(): bool
    {
        $this->load();

        if (!$this->fs->isFile('var/cache/index.php')) {
            return true;
        }

        $check = (bool) $this->config->get('cache.check', true);

        if (!$check) {
            return false;
        }

        foreach ($this->storage->scan() as $id) {
            if ($this->fs->mtime($this->storage->base() . '/' . ($id === '' ? '' : $id)) > $this->stamp) {
                return true;
            }
        }

        return false;
    }

    public function stamp(): int
    {
        return $this->stamp;
    }

    /**
     * Acquire an exclusive lock so a rebuild cannot run in parallel.
     * Returns a callable that releases the lock, or null when the lock is taken.
     */
    public function lock(): ?callable
    {
        $this->fs->ensureDir('var/cache');
        $handle = @fopen($this->fs->path('var/cache/index.lock'), 'c');
        if ($handle === false) {
            return null;
        }

        if (!flock($handle, LOCK_EX | LOCK_NB)) {
            fclose($handle);

            return null;
        }

        return static function () use ($handle): void {
            flock($handle, LOCK_UN);
            fclose($handle);
        };
    }

    private function load(): void
    {
        if ($this->loaded) {
            return;
        }
        $this->loaded = true;

        $file = $this->fs->path('var/cache/index.php');
        if (!is_file($file)) {
            return;
        }

        $data = include $file;
        if (is_array($data)) {
            $this->entries = is_array($data['entries'] ?? null) ? $data['entries'] : [];
            $this->stamp = (int) ($data['stamp'] ?? 0);
        }
    }

    private function persist(): void
    {
        $payload = ['stamp' => $this->stamp, 'entries' => $this->entries];
        $code = "<?php\n\n// Generated by FlatCMS Index. Do not edit.\nreturn " . var_export($payload, true) . ";\n";
        $this->fs->write('var/cache/index.php', $code);
    }

    /**
     * @return array<string, mixed>
     */
    private function indexedValues(Item $item): array
    {
        $values = [];
        foreach ($this->schema->indexedFields($item->type()) as $field) {
            $values[$field] = $item->get($field);
        }

        return $values;
    }
}
